const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {performance} = require('node:perf_hooks');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'trace-recorder-'));
process.env.PI_CODING_AGENT_DIR = dir;
process.env.PI_TRACE_WEB_PORT = '4317';
const jiti = require(process.env.PI_TRACE_TEST_JITI || 'jiti').createJiti(__filename);
const extension = jiti(path.join(__dirname, '..', 'extensions', 'trace', 'index.ts')).default;
const events = new Map();
extension({on(name, fn) { events.set(name, fn); }, registerCommand() {}});
const ctx = {cwd: dir, sessionManager: {getSessionFile() {return path.join(dir, 'test-session.jsonl');}}};
events.get('session_start')({}, ctx);
events.get('before_agent_start')({prompt: 'test'});
events.get('turn_start')({turnIndex: 1});
const history = Array.from({length: 10000}, (_, i) => ({role: 'user', content: 'message ' + i + ' ' + 'x'.repeat(10000)}));
const begin = performance.now();
events.get('before_provider_request')({payload: {model: 'test', messages: history, tools: [{name: 'read', parameters: {description: 'x'.repeat(100000)}}]}});
const elapsed = performance.now() - begin;
const partial = {role: 'assistant', content: [{type: 'thinking', thinking: 'do not reread this snapshot'}]};
for (let i=0; i<1000; i++) events.get('message_update')({message: partial, assistantMessageEvent: {type: 'thinking_delta', delta: 'a', partial}});
events.get('message_end')({message: {role: 'assistant', content: [{type: 'text', text: 'answer'}], usage: {input: 1, output: 2}, stopReason: 'stop'}});
events.get('turn_end')({});
const close = performance.now();
events.get('session_shutdown')({});
const closeMs = performance.now() - close;
setTimeout(() => {
  const file = path.join(dir, 'traces', 'test-session', 'events.jsonl');
  const recorded = fs.readFileSync(file, 'utf8').trim().split('\n').map(JSON.parse);
  const request = recorded.find(e => e.type === 'llm_request');
  assert.equal(request.input.messageCount, 10000);
  assert.equal(request.input.messages.length, 1);
  assert.equal(request.input.tools[0].parameters, undefined);
  assert.ok(JSON.stringify(request).length < 10000);
  const step = recorded.find(e => e.type === 'step_end');
  assert.equal(step.thinking, 'a'.repeat(1000));
  const turn = recorded.find(e => e.type === 'turn_summary');
  assert.equal(turn.steps[0].thinking, undefined);
  assert.equal(fs.existsSync(path.join(dir, 'traces', 'test-session', 'trace.html')), false);
  console.log(JSON.stringify({passed: true, historyMessages: history.length, requestMs: elapsed, shutdownMs: closeMs, requestBytes: JSON.stringify(request).length}));
  fs.rmSync(dir, {recursive: true, force: true});
  process.exit(0);
}, 200);
